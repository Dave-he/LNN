def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--num-train", type=int, default=512)
    parser.add_argument("--num-val", type=int, default=128)
    parser.add_argument("--seq-len", type=int, default=20)
    parser.add_argument("--input-size", type=int, default=16)
    parser.add_argument("--hidden-size", type=int, default=15,
                        help="For rlstg, ambient = hidden+1 must match input_size (16) for fair fold.")
    parser.add_argument("--epochs", type=int, default=5)
    parser.add_argument("--lr", type=float, default=3e-3)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--backbones", nargs="+", default=["cfc", "ltc", "gru", "rlstg"])
    parser.add_argument("--device", default="cpu")
    parser.add_argument("--output-dir", default="analysis/rlstg")
    args = parser.parse_args()

    if args.device == "auto":
        device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    else:
        device = torch.device(args.device)

    rng = torch.Generator().manual_seed(args.seed)
    train_data = _make_sequence_batch(rng, args.num_train, args.seq_len, args.input_size)
    val_data = _make_sequence_batch(rng, args.num_val, args.seq_len, args.input_size)

    print(f"=== RLSTG stage C smoke (iter#38) — {args.backbones} ===")
    print(f"  train {args.num_train} | val {args.num_val} | seq_len {args.seq_len} | hidden {args.hidden_size}")
    results = []
    for backbone in args.backbones:
        try:
            r = _train_eval(backbone, train_data, val_data, args, device)
        except Exception as e:
            print(f"  {backbone}: FAILED — {e}")
            continue
        results.append(r)
        print(f"  {backbone:8s} acc={r['acc']:.4f} aux={r['aux_loss_proxy']:.4f} "
              f"params={r['params']:>5d} train={r['train_seconds']:.2f}s")

    # Aggregate
    by_bb: dict[str, list[dict]] = {}
    for r in results:
        by_bb.setdefault(r["backbone"], []).append(r)

    now = dt.datetime.now()
    run_id = now.strftime("%Y-%m-%d_%H%M%S")
    payload = {
        "run_id": run_id,
        "generated_at": now.isoformat(timespec="seconds"),
        "config": vars(args),
        "results": results,
        "summary": {
            bb: {
                "n_seeds": len(rs),
                "acc_mean": statistics.fmean(r["acc"] for r in rs),
                "acc_std": statistics.pstdev(r["acc"] for r in rs) if len(rs) > 1 else 0.0,
                "params_mean": int(statistics.fmean(r["params"] for r in rs)),
            }
            for bb, rs in by_bb.items()
        },
    }
    out_dir = pathlib.Path(args.output_dir)
    if not out_dir.is_absolute():
        out_dir = ROOT / out_dir
    out_dir.mkdir(parents=True, exist_ok=True)
    json_path = out_dir / f"{run_id}_rlstg_smoke.json"
    md_path = out_dir / f"{run_id}_rlstg_smoke.md"
    with open(json_path, "w") as f:
        json.dump(payload, f, indent=2)
    md_path.write_text(_format_md(payload), encoding="utf-8")
    print(f"  wrote JSON: {json_path}")
    print(f"  wrote MD:   {md_path}")
    return 0


def _format_md(payload: dict) -> str:
    lines = [
        "# RLSTG stage C smoke — synthetic hyperbolic sequence ablation",
        "",
        f"_Generated: {payload['generated_at']}_",
        f"_Source: scripts/experiment_rlstg_smoke.py (iter#38, RLSTG §10 stage C)_",
        f"_Paper: arXiv 2601.14115v1 (Lu et al. WWW '26)_",
        "",
        "## Setup",
        f"- num_train={payload['config']['num_train']} | num_val={payload['config']['num_val']}",
        f"- seq_len={payload['config']['seq_len']} | input_size={payload['config']['input_size']}",
        f"- hidden_size={payload['config']['hidden_size']} (RLSTG ambient = hidden+1 = 16 = input_size)",
        f"- epochs={payload['config']['epochs']} | seed={payload['config']['seed']}",
        "",
        "## Per-seed results",
        "",
        "| Backbone | seed | acc | aux_loss_proxy | params | train_s |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    for r in payload["results"]:
        lines.append(
            f"| {r['backbone']} | {r['seed']} | {r['acc']:.4f} | "
            f"{r['aux_loss_proxy']:.4f} | {r['params']:>5d} | {r['train_seconds']:.2f} |"
        )
    lines.extend([
        "",
        "## Summary",
        "",
        "| Backbone | n_seeds | acc_mean | acc_std | params_mean |",
        "|---|---:|---:|---:|---:|",
    ])
    for bb, s in payload["summary"].items():
        lines.append(
            f"| {bb} | {s['n_seeds']} | {s['acc_mean']:.4f} | "
            f"{s['acc_std']:.4f} | {s['params_mean']} |"
        )
    lines.extend([
        "",
        "## Verdict",
        "",
        "- **Stage-B 限制**: RiemannianLTCNetwork 退到 origin-only expmap0/logmap0,",
        "  不连续 tangent space 推进 — 与论文 full Riemannian ODE 不同。",
        "  本表是 smoke 验证 **「Riemannian wrapper 端到端可训练」**, 不是",
        "  论文 headline 结果的复现。",
        "- 期待: 4 backbones 全部 > 0.55 (chance), 说明 Riemannian wrapper",
        "  能用于实际训练。RLSTG 是否真赢需 full expmap (stage D 升级) +",
        "  论文 ENRON-style 数据 (无开源)。",
    ])
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    sys.exit(main())
